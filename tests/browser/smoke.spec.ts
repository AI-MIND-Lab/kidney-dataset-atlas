import { expect, test } from '@playwright/test';

test('explorer to dataset, paper, search, comparison, and CSV export', async ({ page }) => {
	await page.goto('./');
	await expect(page.getByRole('heading', { name: 'Kidney Dataset Atlas' })).toBeVisible();

	const explorerSearch = page.getByLabel('Search datasets');
	await explorerSearch.fill('renal ct');
	await expect(page).toHaveURL(/\?q=renal\+ct$/);
	await expect(page.locator('[data-count]')).toHaveText('1 dataset of 3');
	await page.getByRole('link', { name: 'Fixture Renal CT Collection (synthetic)' }).first().click();

	await expect(page.getByRole('heading', { level: 1, name: 'Fixture Renal CT Collection (synthetic)' })).toBeVisible();
	await page.getByRole('link', { name: 'Data dictionary' }).click();
	await expect(page.getByRole('heading', { level: 2, name: 'Data dictionary' })).toBeVisible();
	await expect(page.getByText('case_id', { exact: true })).toBeVisible();

	await page.getByRole('link', { name: 'A synthetic paper about a synthetic dataset' }).click();
	await expect(page.getByRole('heading', { level: 1, name: 'A synthetic paper about a synthetic dataset' })).toBeVisible();
	await expect(page.getByRole('columnheader', { name: 'Release or cohort' }).first()).toBeVisible();
	// Results: one row per value, with the split and any patient-level handling shown together.
	await expect(page.getByRole('heading', { level: 2, name: 'Reported results' })).toBeVisible();
	await expect(page.getByRole('columnheader', { name: 'Evaluated on' })).toBeVisible();
	await expect(page.getByRole('columnheader', { name: 'Split', exact: true }).first()).toBeVisible();
	await expect(page.getByText('Invented patient-level split').first()).toBeVisible();
	// A result recorded against two releases is shown once.
	await expect(page.locator('.results-table tbody tr').filter({ hasText: '0.87' })).toHaveCount(1);

	// Architecture: the reproduced figure with its credit and licence, the linked figure, the atlas diagram,
	// the model table and the wording note.
	const figure = page.locator('figure.paper-figure');
	await expect(figure.getByRole('img', { name: /Synthetic diagram/ })).toBeVisible();
	await expect(figure).toContainText('Figure 1 of the paper');
	await expect(figure.getByRole('link', { name: 'CC BY 4.0' })).toHaveAttribute('href', 'https://creativecommons.org/licenses/by/4.0/');
	await expect(page.getByRole('link', { name: 'View figure 2 in the paper' })).toBeVisible();
	await expect(page.locator('.pipeline__label')).toHaveText(['Synthetic CT', 'FixtureNet', 'Invented mask']);
	await expect(page.locator('.model-table')).toContainText('How it works');
	await expect(page.locator('.model-table')).toContainText('Invented slice aggregation');
	await expect(page.locator('.model-table__provenance')).toContainText('invented methods section and Figure 1');
	await expect(page.getByText('Fixture private hospital cohort')).toBeVisible();
	await expect(page.getByText('Fixture private hospital cohort').locator('a')).toHaveCount(0);

	await page.locator('.site-search input').fill('FixtureNet');
	await page.locator('.site-search input').press('Enter');
	await expect(page).toHaveURL(/\/search\/\?q=FixtureNet$/);
	await expect(page.locator('[data-search-status]')).toContainText(/result/);
	await expect(page.locator('[data-search-results]')).toContainText('A synthetic paper about a synthetic dataset');

	await page.getByRole('navigation', { name: 'Primary' }).getByRole('link', { name: 'Compare' }).click();
	await page.getByRole('checkbox', { name: /Fixture Renal CT Collection.*v2/ }).check();
	await page.getByRole('checkbox', { name: /Fixture Pathology Slide Set/ }).check();
	await expect(page.locator('[data-compare-table]')).toBeVisible();
	await expect(page.locator('.compare-table')).toContainText('Fixture Renal CT Collection');

	const downloadPromise = page.waitForEvent('download');
	await page.getByRole('button', { name: 'Download CSV' }).click();
	const download = await downloadPromise;
	expect(download.suggestedFilename()).toMatch(/^comparison-.*\.csv$/);
});

test('previews show facts and provider text, and open large when clicked', async ({ page }) => {
	await page.goto('./datasets/fixture-renal-ct/');
	const previews = page.locator('#samples [data-sample]');
	await expect(previews).toHaveCount(2);

	// Under each image: the case, who drew the mask, and the provider's own words, marked when a program wrote them.
	const stack = previews.filter({ hasText: 'FX-0001' });
	await expect(stack).toContainText('Mask: Invented lesion mask');
	await expect(stack).toContainText('Machine-generated by the provider (a fixture generator)');
	const figure = previews.filter({ hasText: 'Figure 1' });
	await expect(figure).toContainText('From the provider:');
	await expect(figure.locator('dd')).toHaveText('“A single synthetic figure, with no slice stack and no mask, so the viewer shows no controls.”');
	// How to read the previews and their credit appear once for the group, not under each image.
	await expect(page.locator('#samples summary', { hasText: 'Credit and licence' })).toHaveCount(1);

	// Clicking opens the large copy where one exists; arrows step through; Escape closes.
	await figure.getByRole('button', { name: 'Enlarge the preview of Figure 1' }).click();
	const lightbox = page.locator('[data-lightbox]');
	await expect(lightbox).toBeVisible();
	await expect(lightbox.locator('[data-lightbox-image]')).toHaveAttribute('src', /figure-large\.svg$/);
	await expect(lightbox.locator('[data-lightbox-title]')).toHaveText('Figure 1');
	await page.keyboard.press('ArrowRight');
	await expect(lightbox.locator('[data-lightbox-title]')).toHaveText('FX-0001');
	await lightbox.getByRole('button', { name: 'Actual size' }).click();
	await expect(lightbox.locator('[data-lightbox-stage]')).toHaveClass(/is-actual/);
	await page.keyboard.press('Escape');
	await expect(lightbox).toBeHidden();
});
